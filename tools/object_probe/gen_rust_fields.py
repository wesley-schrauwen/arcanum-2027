"""Generates crates/arcanum_formats/src/object_fields.rs from the engine's field enum.

Inputs (this directory):
- obj_field_names_reversed.txt: the 338 `obj_f_*` names from Arcanum.exe, in reverse enum order.
- ftypes.json: the engine's storage kind per field index (entry+0x18 of the field table, set
  statically in FUN_0040a8a0 .. 0x40b8d5; extracted from a disassembly).

usage: python3 -I tools/object_probe/gen_rust_fields.py > crates/arcanum_formats/src/object_fields.rs
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
NAMES = [l.strip()[6:] for l in reversed(open(os.path.join(HERE, 'obj_field_names_reversed.txt')).read().split())]
KINDS = {int(k): v for k, v in json.load(open(os.path.join(HERE, 'ftypes.json'))).items()}

# (const name, begin marker, end marker, doc); fields are begin+1 .. end-1.
BLOCKS = [
    ('COMMON', 'begin', 'end', 'Fields every object has (bitmap bits 0..).'),
    ('WALL', 'wall_begin', 'wall_end', 'Wall fields (type 0, bits 64..).'),
    ('PORTAL', 'portal_begin', 'portal_end', 'Portal fields (type 1, bits 64..).'),
    ('CONTAINER', 'container_begin', 'container_end', 'Container fields (type 2, bits 64..).'),
    ('SCENERY', 'scenery_begin', 'scenery_end', 'Scenery fields (type 3, bits 64..).'),
    ('PROJECTILE', 'projectile_begin', 'projectile_end', 'Projectile fields (type 4, bits 64..).'),
    ('ITEM', 'item_begin', 'item_end', 'Fields every item has (types 5-14, bits 64..).'),
    ('WEAPON', 'weapon_begin', 'weapon_end', 'Weapon fields (type 5, bits 96..).'),
    ('AMMO', 'ammo_begin', 'ammo_end', 'Ammunition fields (type 6, bits 96..).'),
    ('ARMOR', 'armor_begin', 'armor_end', 'Armor fields (type 7, bits 96..).'),
    ('GOLD', 'gold_begin', 'gold_end', 'Gold fields (type 8, bits 96..).'),
    ('FOOD', 'food_begin', 'food_end', 'Food fields (type 9, bits 96..).'),
    ('SCROLL', 'scroll_begin', 'scroll_end', 'Scroll fields (type 10, bits 96..).'),
    ('KEY', 'key_begin', 'key_end', 'Key fields (type 11, bits 96..).'),
    ('KEY_RING', 'key_ring_begin', 'key_ring_end', 'Key ring fields (type 12, bits 96..).'),
    ('WRITTEN', 'written_begin', 'written_end', 'Written item fields (type 13, bits 96..).'),
    ('GENERIC', 'generic_begin', 'generic_end', 'Generic item fields (type 14, bits 96..).'),
    ('CRITTER', 'critter_begin', 'critter_end', 'Fields every critter has (types 15-16, bits 64..).'),
    ('PC', 'pc_begin', 'pc_end', 'Player-character fields (type 15, bits 128..).'),
    ('NPC', 'npc_begin', 'npc_end', 'Non-player-character fields (type 16, bits 128..).'),
    ('TRAP', 'trap_begin', 'trap_end', 'Trap fields (type 17, bits 64..).'),
]


def storage(kind):
    if kind == 3:
        return 'Int32'
    if kind == 4:
        return 'Int64'
    if kind == 11:
        return 'String'
    if kind == 12:
        return 'ObjectRef'
    if kind in (5, 6, 7, 8, 9, 10, 13):
        return 'Array'
    raise ValueError(kind)


print('//! Object field tables, one per type block. Generated by `tools/object_probe/gen_rust_fields.py`')
print('//! from the engine\'s `obj_f_*` enum (names) and its static storage-kind table (`FUN_0040a8a0`);')
print('//! do not edit by hand.')
print()
print('use crate::object::{FieldDef, Storage};')
for const, begin, end, doc in BLOCKS:
    i, j = NAMES.index(begin), NAMES.index(end)
    print()
    print(f'/// {doc}')
    print(f'pub const {const}_FIELDS: [FieldDef; {j - i - 1}] = [')
    for idx in range(i + 1, j):
        print(f'    FieldDef {{ id: {idx}, name: "{NAMES[idx]}", storage: Storage::{storage(KINDS[idx])} }},')
    print('];')
